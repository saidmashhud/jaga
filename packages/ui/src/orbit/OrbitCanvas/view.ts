/**
 * Приближение и панорама — арифметика отдельно от разметки.
 *
 * Отдельно потому, что здесь легко ошибиться незаметно: приближение «к
 * курсору» отличается от приближения «к центру» одной строкой, а на экране
 * разница огромна — в первом случае колесо это способ прицелиться, во втором
 * человек увеличивает и потом ищет, куда всё уехало.
 */

export interface View {
  /** Ручное приближение поверх вписывающего масштаба. */
  zoom: number;
  /** Сдвиг полотна в пикселях экрана. */
  x: number;
  y: number;
}

export const RESET: View = { zoom: 1, x: 0, y: 0 };

/** Пределы приближения. Ниже — сцена мельче кегля подписи, выше — теряется целое. */
export const MIN_ZOOM = 0.5;
export const MAX_ZOOM = 4;

export function clampZoom(z: number): number {
  return Math.min(MAX_ZOOM, Math.max(MIN_ZOOM, z));
}

/**
 * Приближение к точке под курсором.
 *
 * Точка сцены, оказавшаяся под курсором, обязана остаться под ним и после.
 * Отсюда и вся арифметика: сдвиг подбирается так, чтобы неподвижной осталась
 * именно она, а не центр экрана.
 *
 * @param view    нынешнее состояние
 * @param factor  во сколько раз приблизить (>1 — ближе)
 * @param px      курсор относительно центра полотна, в пикселях
 * @param py      то же по вертикали
 */
export function zoomAt(view: View, factor: number, px: number, py: number): View {
  const next = clampZoom(view.zoom * factor);
  // Если упёрлись в предел, двигать нечего: иначе колесо на пределе начинало
  // бы возить сцену вбок.
  if (next === view.zoom) return view;
  const k = next / view.zoom;
  return {
    zoom: next,
    x: px - (px - view.x) * k,
    y: py - (py - view.y) * k,
  };
}

/** Шаг колеса → множитель. Плавно и без рывков на разных устройствах. */
export function wheelFactor(deltaY: number): number {
  // Ограничение обязательно: трекпад шлёт мелкие частые события, мышь — редкие
  // и крупные, а «мышь с ускорением» изредка выдаёт разом сотни единиц, от
  // которых сцена прыгала бы через весь диапазон за один щелчок.
  const d = Math.max(-120, Math.min(120, deltaY));
  return Math.exp(-d * 0.0016);
}
