// Package layout — расположение проектов на сцене.
//
// До этого координаты лежали в данных: шесть проектов стояли там, куда их
// поставил человек. Это работало ровно до седьмого — новый проект приходилось
// вписывать руками, а настоящий набор раскладывать было нечем.
//
// Считается на сервере, а не в сцене: позиции потребляют обе реализации —
// трёхмерная и запасная на SVG, — и два алгоритма разошлись бы в первый же
// день. Сцена рисует то, что ей дали, и не решает, где чему быть.
package layout

import (
	"math"
	"sort"
)

// Ось внимания.
//
// Это не украшение: ради этого смысла сцена и сделана — ближе к человеку то,
// что требует его решения, дальше то, что отложено. Сцена стала плоской, и
// смысл переехал из глубины в РАССТОЯНИЕ ОТ ЯДРА: пояс вместо этажа. Иначе
// плоский граф красиво показывал бы связи и не утверждал бы ничего.
//
// Перечислены все статусы, какие есть в данных. Незнакомый не проваливается
// молча: раньше так вёл себя «working», и поведение оказалось верным по
// совпадению, а не по решению — следующий незнакомый встал бы туда же и никто
// бы не заметил.
type Belt struct {
	// Номер от ядра наружу, 1..6. Он попадает в подпись узла для читалки
	// («пояс 2 из 6»), поэтому это часть договора, а не порядковый номер в
	// массиве.
	Index int `json:"index"`
	// Расстояние от ядра.
	Radius float64 `json:"radius"`
	// Допуск: внутри полосы узел свободен, за неё не выходит никогда.
	Band float64 `json:"band"`
}

var belts = map[string]Belt{
	"decision":  {1, 112, 8}, // ждёт решения — ближе всего
	"risk":      {2, 160, 8}, // угрожает — тоже рядом
	"attention": {3, 208, 8}, // требует внимания
	"working":   {4, 254, 8}, // идёт своим ходом
	"stable":    {5, 298, 8}, // не требует ничего
	"paused":    {6, 340, 8}, // отложено — дальше всех
}

// Порядок поясов от ядра наружу. Карта в Go обходится случайно, а порядок
// здесь — часть картинки.
var beltOrder = []string{"decision", "risk", "attention", "working", "stable", "paused"}

// Черта решения — между третьим и четвёртым поясом.
//
// Шесть ступеней сводятся к одному вопросу: ждёт это вас или идёт само.
// Внутри черты — то, что без вас не двинется.
const DecisionRadius = 231

// Незнакомому статусу достаётся пояс «в работе» — но об этом говорится вслух
// и в журнал, и в ответе, а не подставляется молча.
const fallbackBelt = "working"

// Belts отдаёт пояса в порядке от ядра наружу — сцене, чтобы она не заводила
// собственную таблицу радиусов. Два словаря в разных местах разошлись бы при
// первом же добавлении состояния; так уже вышло с цветами связей.
func Belts() []struct {
	Status string `json:"status"`
	Belt
} {
	out := make([]struct {
		Status string `json:"status"`
		Belt
	}, 0, len(beltOrder))
	for _, st := range beltOrder {
		out = append(out, struct {
			Status string `json:"status"`
			Belt
		}{st, belts[st]})
	}
	return out
}

// BeltOf — пояс состояния и признак того, что он угадан, а не известен.
func BeltOf(status string) (Belt, bool) {
	b, ok := belts[status]
	if !ok {
		return belts[fallbackBelt], false
	}
	return b, true
}

// UnknownStatuses возвращает статусы, для которых ось внимания не определена.
//
// Отдельной функцией, чтобы служба могла о них сказать в журнал: молчаливое
// значение по умолчанию — это способ не узнать о новом статусе никогда.
func UnknownStatuses(nodes []Node) []string {
	seen := map[string]bool{}
	var out []string
	for _, n := range nodes {
		if _, ok := belts[n.Status]; !ok && !seen[n.Status] {
			seen[n.Status] = true
			out = append(out, n.Status)
		}
	}
	sort.Strings(out)
	return out
}

// Node — то, что раскладывается.
type Node struct {
	ID     string
	Status string
}

// Edge — связь между проектами. Сила влияет на то, насколько близко их тянет.
type Edge struct {
	Source, Target string
	Strength       int
}

// Point — куда встал узел.
// Point — место узла на сцене.
//
// Z остаётся в ответе числом: контракт читают и другие места, ломать его
// заодно с переходом на плоскую сцену незачем. Но сцена его больше не рисует —
// глубину заменил пояс.
type Point struct {
	X, Y, Z float64
	// Belt — номер пояса от ядра, 1..6.
	Belt int
	// BeltGuessed — состояние незнакомо, пояс подставлен. Сцена показывает
	// такой узел пунктиром: молчаливая догадка хуже видимой.
	BeltGuessed bool
}

// Логическое пространство сцены. Те же величины, в которых были записаны
// авторские координаты, — иначе пришлось бы пересчитывать масштаб сцены.
const (
	centerX = 600
	centerY = 400
	// Ширина и высота логического поля — сцена вписывает их в свои размеры.
	// Отдаются наружу вместе с поясами, чтобы у страницы не было своей копии.
	SceneWidth  = 1200
	SceneHeight = 800
	CenterX     = centerX
	CenterY     = centerY
)

// Compute раскладывает узлы.
//
// Алгоритм пружинный, но полностью предсказуемый: начальные места берутся из
// порядка идентификаторов, случайности нет нигде. Это условие, а не вкус —
// сцена, переставляющая проекты при каждой перезагрузке, не даёт запомнить,
// где что лежит, и человек ищет заново то, что уже находил.
func Compute(nodes []Node, edges []Edge) map[string]Point {
	out := make(map[string]Point, len(nodes))
	if len(nodes) == 0 {
		return out
	}

	// Порядок фиксируем: карта в Go обходится в случайном порядке, и без
	// сортировки раскладка менялась бы от запроса к запросу.
	ordered := make([]Node, len(nodes))
	copy(ordered, nodes)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].ID < ordered[j].ID })

	idx := make(map[string]int, len(ordered))
	px := make([]float64, len(ordered))
	py := make([]float64, len(ordered))

	// Начальная расстановка — сразу по своим поясам, равными углами.
	//
	// Не по общему кольцу: узел, начавший на чужом радиусе, первым же шагом
	// прыгает на свой, и соседи разлетаются от этого рывка. Фаза у каждого
	// пояса своя, иначе пояса выстроились бы столбиками, как спицы.
	band := make([]float64, len(ordered))
	beltIdx := make([]int, len(ordered))
	known := make([]bool, len(ordered))
	byBelt := map[int][]int{}
	for i, n := range ordered {
		idx[n.ID] = i
		b, ok := BeltOf(n.Status)
		beltIdx[i] = b.Index
		known[i] = ok
		byBelt[b.Index] = append(byBelt[b.Index], i)
	}
	for bi, list := range byBelt {
		b := belts[beltOrder[bi-1]]
		w := b.Band
		// Переполненный пояс расширяется и укладывается в две нити. Восемнадцать
		// — меньше половины любого межпоясного зазора, поэтому пояс остаётся
		// узнаваемым, а десяток срочных дел не слипается в одну гирлянду.
		if 2*math.Pi*b.Radius < float64(len(list))*62 {
			w = 18
		}
		for k, i := range list {
			band[i] = w
			// Смещение из имени узла. Случайности здесь нет — от одного и того
			// же набора всегда получается одна и та же картинка, — но строгая
			// симметрия ломается. Она вредна: два узла, вставшие ровно напротив
			// друг друга, тянутся связью точно по радиусу, а радиус закреплён
			// поясом. Тангенциальной силы нет вовсе, и пара застревает
			// в неустойчивом равновесии по разные стороны ядра.
			a := 0.37*float64(bi) + 2*math.Pi*float64(k)/float64(len(list)) + nudge(ordered[i].ID)
			r := b.Radius
			if w > b.Band && k%2 == 1 {
				r += 0.7 * w
			} else if w > b.Band {
				r -= 0.7 * w
			}
			px[i] = centerX + r*math.Cos(a)
			py[i] = centerY + r*math.Sin(a)
		}
	}

	// Связанные притягиваются, все прочие отталкиваются. Сорока проходов
	// хватает: узлов здесь десятки, а не тысячи, и дальше картинка уже не
	// меняется на глаз.
	// Проходов много не для точности, а для сходимости.
	//
	// Сорока хватало, пока узлы ходили по всей плоскости. На поясе они ходят
	// только вдоль кольца, и слабая связь ползёт по дуге медленно: при 120
	// проходах пара с силой 1 не доходила до своего места и вставала там, где
	// её застал последний проход, — то есть раскладка зависела не от сил, а от
	// того, где оборвался счёт. Замерено: равновесие достигается к 480, дальше
	// картинка не меняется вовсе.
	const passes = 480
	for pass := 0; pass < passes; pass++ {
		// Шаг убывает: крупные перестановки в начале, доводка в конце.
		// Постоянный шаг заставляет узлы колебаться вокруг своих мест и
		// никогда не встать окончательно.
		step := 1.0 - float64(pass)/float64(passes)

		dx := make([]float64, len(ordered))
		dy := make([]float64, len(ordered))

		// Отталкивание: каждый от каждого, обратно расстоянию.
		for i := range ordered {
			for j := i + 1; j < len(ordered); j++ {
				vx, vy := px[i]-px[j], py[i]-py[j]
				d2 := vx*vx + vy*vy
				if d2 < 1 {
					// Совпавшие узлы разводим по оси — иначе сила
					// бесконечна, а направление не определено.
					vx, vy, d2 = 1, 0, 1
				}
				// Кламп по расстоянию обязателен: без него сила на сблизившихся
				// узлах взлетает до небес, и подобрать остальные константы
				// становится нельзя — они всё время воюют с этим всплеском.
				if d2 < 900 {
					d2 = 900
				}
				f := 130000 / d2
				d := math.Sqrt(d2)
				dx[i] += vx / d * f
				dy[i] += vy / d * f
				dx[j] -= vx / d * f
				dy[j] -= vy / d * f
			}
		}

		// Притяжение по связям. Сильная связь тянет заметнее — это то, что
		// человек и ожидает увидеть: тесно связанное стоит рядом.
		for _, e := range edges {
			i, ok1 := idx[e.Source]
			j, ok2 := idx[e.Target]
			if !ok1 || !ok2 || i == j {
				continue
			}
			s := float64(e.Strength)
			if s < 1 {
				s = 1
			}
			vx, vy := px[j]-px[i], py[j]-py[i]
			d := math.Hypot(vx, vy)
			if d < 1 {
				continue
			}
			// Длина покоя 110, а не 260: внутренний пояс всего 224 в поперечнике,
			// и пружина с прежним покоем РАСТАЛКИВАЛА бы связанных на
			// противоположные концы кольца вместо того, чтобы сводить.
			f := clamp((d-110)*0.03*s, 40)
			dx[i] += vx / d * f
			dy[i] += vy / d * f
			dx[j] -= vx / d * f
			dy[j] -= vy / d * f
		}

		for i := range ordered {
			// Поперечная часть силы срезается.
			//
			// Узел свободен вдоль пояса и закреплён поперёк, поэтому радиальная
			// часть всё равно будет отменена проекцией — но по дороге она
			// съедает шаг и создаёт мёртвые точки: у пары, стоящей друг против
			// друга, вся сила связи как раз радиальная, и узлы не двигались
			// вовсе. Оставляем только то, что вправду может их сдвинуть.
			vx, vy := px[i]-centerX, py[i]-centerY
			if r := math.Hypot(vx, vy); r > 0.001 {
				nx, ny := vx/r, vy/r
				radial := dx[i]*nx + dy[i]*ny
				dx[i] -= radial * nx
				dy[i] -= radial * ny
			}

			px[i] += clamp(dx[i], 60) * step
			py[i] += clamp(dy[i], 60) * step

			// Возврат в полосу своего пояса.
			//
			// Радиус здесь не сила, а связь: узел свободен вдоль кольца и
			// несвободен поперёк. Силой это сделать нельзя — достаточно
			// сильная связь всё равно утащила бы узел на чужой пояс, и
			// расстояние от ядра перестало бы что-либо означать. А означает
			// оно главное: насколько дело требует человека.
			ox, oy := px[i]-centerX, py[i]-centerY
			r := math.Hypot(ox, oy)
			if r < 0.001 {
				ox, oy, r = 1, 0, 1
			}
			target := belts[beltOrder[beltIdx[i]-1]].Radius
			want := math.Max(target-band[i], math.Min(target+band[i], r))
			px[i] = centerX + ox/r*want
			py[i] = centerY + oy/r*want
		}
	}

	for i, n := range ordered {
		out[n.ID] = Point{
			X:           round(px[i]),
			Y:           round(py[i]),
			Belt:        beltIdx[i],
			BeltGuessed: !known[i],
		}
	}
	return out
}

// clamp ограничивает шаг: один пересчёт не должен швырять узел через всю
// сцену, иначе раскладка расходится вместо того, чтобы сойтись.
func clamp(v, max float64) float64 {
	if v > max {
		return max
	}
	if v < -max {
		return -max
	}
	return v
}

func round(v float64) float64 { return math.Round(v*10) / 10 }

// nudge — крошечное смещение угла, выведенное из имени узла.
//
// Нужно ровно затем, чтобы сломать строгую симметрию расстановки: она даёт
// мёртвые точки, из которых силы вывести узел не могут. Величина меньше
// градуса — глазом не видно, а равновесие уже не идеальное. Выведено из имени,
// а не взято случайно: раскладка обязана повторяться от запуска к запуску.
func nudge(id string) float64 {
	var h uint32 = 2166136261
	for i := 0; i < len(id); i++ {
		h ^= uint32(id[i])
		h *= 16777619
	}
	return (float64(h%1000)/1000 - 0.5) * 0.03
}
