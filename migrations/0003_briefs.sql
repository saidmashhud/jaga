-- Утренний бриф: что сегодня заслуживает внимания.
--
-- Ранг считают правила по данным, слова пишет модель. Так обходится её
-- главное ограничение: она отвечает минутами, и потому работает один раз
-- в день фоном, а не на каждый взгляд человека.
--
-- Хранится по дню: бриф — это суждение на утро, а не живой поток. Пересборка
-- в течение дня перезаписывает строку того же дня, а не плодит новые.
CREATE TABLE briefs (
    tenant_id   TEXT  NOT NULL,
    day         DATE  NOT NULL,
    title       TEXT  NOT NULL,
    body        TEXT  NOT NULL,
    -- Причины — от правил, не от модели: они должны быть проверяемыми
    -- фактами («2 дела высокого эффекта открыты»), а не сочинением.
    reasons     JSONB NOT NULL DEFAULT '[]',
    project_ids JSONB NOT NULL DEFAULT '[]',
    -- Сырой ответ модели рядом: разбор можно пересмотреть, не гоняя её заново.
    model_raw   TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, day)
);
